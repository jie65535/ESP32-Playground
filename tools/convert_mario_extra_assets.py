def safe_name(value: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", value)


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red * 31 // 255) << 11) | ((green * 63 // 255) << 5) | (
        blue * 31 // 255
    )


def emit(values: list[int], value_type: str, per_line: int) -> str:
    lines = []
    for offset in range(0, len(values), per_line):
        chunk = values[offset : offset + per_line]
        if value_type == "uint16_t":
            values_text = ", ".join(f"0x{value:04X}" for value in chunk)
        else:
            values_text = ", ".join(str(value) for value in chunk)
        lines.append("    " + values_text)
    return ",\n".join(lines)


def generate(source_root: Path, output: Path) -> None:
    graphics = source_root / "resources" / "graphics"
    lines = [
        "// Generated by tools/convert_mario_extra_assets.py; do not edit by hand.",
        "#pragma once",
        "",
        "#include <cstdint>",
        '#include "ui/PixelSprite.h"',
        "",
        "namespace pgos::platformer_extra_assets {",
        "",
        "using Frame = pgos::PixelSprite;",
        "",
    ]
    names = []
    for name, sheet_name, x, y, width, height in FRAME_SPECS:
        with Image.open(graphics / sheet_name) as sheet:
            frame = sheet.convert("RGBA").crop((x, y, x + width, y + height))
        pixels = []
        alpha = []
        pixel_data = getattr(frame, "get_flattened_data", frame.getdata)()
        for red, green, blue, source_alpha in pixel_data:
            pixels.append(rgb565(red, green, blue))
            alpha.append(
                0 if source_alpha == 0 or (red, green, blue) == (0, 0, 0)
                else source_alpha
            )
        packed = []
        for pixel in pixels:
            packed.extend((pixel & 0xFF, (pixel >> 8) & 0xFF))
        packed.extend(alpha)
        symbol = safe_name(name)
        names.append(symbol)
        lines.extend(
            [
                f"inline constexpr uint8_t {symbol}_image_data[] = {{",
                emit(packed, "uint8_t", 24),
                "};",
                f"inline constexpr Frame {symbol} = {{",
                f'    "{name}", {width}, {height},',
                f"    {symbol}_image_data, sizeof({symbol}_image_data), false",
                "};",
                "",
            ]
        )
    lines.append("inline constexpr const Frame* all[] = {")
    lines.extend(f"    &{name}," for name in names)
    lines.extend(["};", "", "}  // namespace pgos::platformer_extra_assets", ""])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {len(names)} frames -> {output}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.source.resolve(), args.output.resolve())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
