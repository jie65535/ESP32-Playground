#!/usr/bin/env python3
"""Convert the remaining Mario-Level-1 runtime frames for PGOS.

The reference project keeps these frames as hard-coded sprite-sheet rectangles
inside its Pygame classes. This converter mirrors those rectangles once at
build time so the firmware only contains immutable RGB565+A8 data.
"""

